"""Base strategy framework and signal types."""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime, timedelta, time
from enum import Enum
from typing import Optional
from collections import defaultdict

from finbot.data.market_state import MarketState


# ===== GLOBAL SIGNAL TRACKER =====
# Tracks signals across all strategies for cooldown and daily limits
_signal_tracker: dict[str, list[datetime]] = defaultdict(list)
_daily_trade_count: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))


def reset_signal_tracker():
    """Reset the global signal tracker (call at start of each trading day)."""
    global _signal_tracker, _daily_trade_count
    _signal_tracker.clear()
    _daily_trade_count.clear()


def record_signal(symbol: str, strategy: str, timestamp: datetime):
    """Record that a signal was generated."""
    _signal_tracker[symbol].append(timestamp)
    date_key = timestamp.strftime("%Y-%m-%d")
    _daily_trade_count[date_key][symbol] += 1


def check_cooldown(symbol: str, current_time: datetime, cooldown_minutes: int = 30) -> bool:
    """
    Check if we're in a cooldown period for this symbol.
    
    Returns True if we're STILL in cooldown (should NOT trade).
    Returns False if cooldown has passed (OK to trade).
    """
    if symbol not in _signal_tracker:
        return False  # No previous signals, not in cooldown
    
    last_signals = _signal_tracker[symbol]
    if not last_signals:
        return False
    
    last_signal_time = max(last_signals)
    time_since_last = current_time - last_signal_time
    
    return time_since_last < timedelta(minutes=cooldown_minutes)


def check_daily_limit(symbol: str, current_time: datetime, max_trades: int = 3) -> bool:
    """
    Check if we've hit the daily trade limit for this symbol.
    
    Returns True if limit REACHED (should NOT trade).
    Returns False if under limit (OK to trade).
    """
    date_key = current_time.strftime("%Y-%m-%d")
    current_count = _daily_trade_count[date_key][symbol]
    return current_count >= max_trades


def is_valid_session(current_time: datetime) -> bool:
    """
    Check if we're in a valid trading session.
    
    Avoid:
    - First 15 minutes (9:15-9:30): Opening volatility & stop hunting
    - Last 30 minutes (15:00-15:30): Squareoff pressure
    
    Returns True if OK to trade, False otherwise.
    """
    market_time = current_time.time()
    
    # Avoid first 15 minutes
    if market_time < time(9, 30):
        return False
    
    # Avoid last 30 minutes
    if market_time >= time(15, 0):
        return False
    
    return True


class SignalType(str, Enum):
    """Signal types."""
    LONG = "LONG"
    SHORT = "SHORT"
    HOLD = "HOLD"
    EXIT_LONG = "EXIT_LONG"
    EXIT_SHORT = "EXIT_SHORT"


class SignalStrength(str, Enum):
    """Signal strength/confidence levels."""
    WEAK = "WEAK"          # 0-40% confidence
    MODERATE = "MODERATE"  # 40-70% confidence
    STRONG = "STRONG"      # 70-90% confidence
    VERY_STRONG = "VERY_STRONG"  # 90%+ confidence


@dataclass
class Signal:
    """
    Trading signal generated by a strategy.
    
    Contains all information needed to execute a trade.
    """
    signal_type: SignalType
    strategy_name: str
    symbol: str
    token: str
    exchange: str
    
    # Confidence
    confidence: float = 0.0  # 0.0 to 1.0
    strength: SignalStrength = SignalStrength.WEAK
    
    # Price levels
    entry_price: Optional[float] = None
    stop_loss: Optional[float] = None
    target: Optional[float] = None
    
    # Risk/Reward
    risk_reward_ratio: float = 0.0
    
    # Context
    reason: str = ""
    indicators: dict = field(default_factory=dict)
    
    # Metadata
    timestamp: datetime = field(default_factory=datetime.now)
    
    def is_actionable(self, min_confidence: float = 0.6) -> bool:
        """Check if signal is actionable based on confidence threshold."""
        return (
            self.signal_type in [SignalType.LONG, SignalType.SHORT] and
            self.confidence >= min_confidence and
            self.stop_loss is not None
        )
    
    def calculate_risk_reward(self) -> float:
        """Calculate risk:reward ratio."""
        if not all([self.entry_price, self.stop_loss, self.target]):
            return 0.0
        
        risk = abs(self.entry_price - self.stop_loss)
        reward = abs(self.target - self.entry_price)
        
        if risk == 0:
            return 0.0
        
        self.risk_reward_ratio = reward / risk
        return self.risk_reward_ratio
    
    def to_dict(self) -> dict:
        """Convert signal to dictionary."""
        return {
            "signal_type": self.signal_type.value,
            "strategy": self.strategy_name,
            "symbol": self.symbol,
            "confidence": self.confidence,
            "strength": self.strength.value,
            "entry_price": self.entry_price,
            "stop_loss": self.stop_loss,
            "target": self.target,
            "risk_reward": self.risk_reward_ratio,
            "reason": self.reason,
            "timestamp": self.timestamp.isoformat(),
        }


class BaseStrategy(ABC):
    """
    Abstract base class for all trading strategies.
    
    Each strategy must implement:
    - evaluate(): Analyze market state and return a signal
    - name: Strategy identifier
    
    Includes institutional-grade filters:
    - Signal cooldown (default 30 min)
    - Daily trade limits (default 3 per symbol)
    - Session timing filters
    """
    
    # Global filter settings (can be overridden per strategy)
    # Institutional discipline: fewer, higher-quality trades
    COOLDOWN_MINUTES = 45  # 45 min between signals per symbol
    MAX_DAILY_TRADES = 2   # Max 2 trades per symbol per day
    ENFORCE_SESSION = True
    
    def __init__(self, enabled: bool = True):
        """Initialize strategy."""
        self.enabled = enabled
        self._last_signal: Optional[Signal] = None
        self._signal_count = 0
    
    @property
    @abstractmethod
    def name(self) -> str:
        """Strategy name identifier."""
        pass
    
    @property
    def description(self) -> str:
        """Strategy description."""
        return ""
    
    @abstractmethod
    def evaluate(self, state: MarketState) -> Signal:
        """
        Evaluate market state and generate a trading signal.
        
        Args:
            state: Current market state with all data
            
        Returns:
            Signal with trade recommendation
        """
        pass
    
    def _create_signal(
        self,
        signal_type: SignalType,
        state: MarketState,
        confidence: float,
        reason: str,
        stop_loss: Optional[float] = None,
        target: Optional[float] = None,
    ) -> Signal:
        """Helper to create a signal with common fields."""
        # Auto-calculate stop loss if not provided
        if stop_loss is None and signal_type in [SignalType.LONG, SignalType.SHORT]:
            side = 'long' if signal_type == SignalType.LONG else 'short'
            stop_loss = state.get_stop_loss(side)
        
        # Auto-calculate target if not provided
        if target is None and stop_loss and signal_type in [SignalType.LONG, SignalType.SHORT]:
            side = 'long' if signal_type == SignalType.LONG else 'short'
            target = state.get_target(side, risk_reward=2.0, stop_loss=stop_loss)
        
        # Determine strength
        if confidence >= 0.9:
            strength = SignalStrength.VERY_STRONG
        elif confidence >= 0.7:
            strength = SignalStrength.STRONG
        elif confidence >= 0.4:
            strength = SignalStrength.MODERATE
        else:
            strength = SignalStrength.WEAK
        
        signal = Signal(
            signal_type=signal_type,
            strategy_name=self.name,
            symbol=state.symbol,
            token=state.token,
            exchange=state.exchange,
            confidence=confidence,
            strength=strength,
            entry_price=state.current_price,
            stop_loss=stop_loss,
            target=target,
            reason=reason,
            indicators={
                "ema_9": state.indicators.ema_9,
                "rsi_14": state.indicators.rsi_14,
                "vwap": state.indicators.vwap,
                "atr": state.indicators.atr_14,
            },
            timestamp=state.current_time
        )
        
        signal.calculate_risk_reward()
        self._last_signal = signal
        self._signal_count += 1
        
        return signal
    
    def _hold_signal(self, state: MarketState, reason: str = "No setup") -> Signal:
        """Create a HOLD signal."""
        return Signal(
            signal_type=SignalType.HOLD,
            strategy_name=self.name,
            symbol=state.symbol,
            token=state.token,
            exchange=state.exchange,
            confidence=0.0,
            reason=reason,
        )
    
    def reset(self) -> None:
        """Reset strategy state."""
        self._last_signal = None
        self._signal_count = 0
